import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { allDiagrams } from "../src/content/diagrams";
import type { DiagramEdge, DiagramNode, ProjectDiagram } from "../src/content/diagrams/types";
import { NODE_H, NODE_W, channelY, nodeX, nodeY } from "../src/components/diagram/geometry";

/**
 * Mermaid and Draw.io, from the same typed model the site renders.
 *
 * The point of generating these rather than drawing them is that there is one source of truth for
 * a project's architecture and three renderings of it. A README that disagrees with the website is
 * the normal end state of hand-maintained diagrams, and it is invisible until someone notices -
 * so the only safe arrangement is that the portable files cannot be edited into disagreement,
 * because editing them is pointless: the next run overwrites them.
 *
 * Draw.io reuses `geometry.ts`, so a diagram opened in diagrams.net has the boxes in the same
 * places as the diagram on the site rather than in a fresh auto-layout nobody recognises.
 *
 *     npm run export:diagrams
 *
 * Output: docs/diagrams/<slug>.mmd and docs/diagrams/<slug>.drawio
 */

const OUT = resolve(import.meta.dirname, "..", "docs", "diagrams");

/* ----------------------------------------------------------------------------------------------
 * Mermaid
 * -------------------------------------------------------------------------------------------- */

/** Node shape per kind. Mermaid has no styling hook that survives GitHub, so shape carries it. */
function mermaidShape(node: DiagramNode): string {
  const text = `"${node.label}"`;
  switch (node.kind) {
    case "source":
      return `${node.id}([${text}])`;
    case "store":
      return `${node.id}[(${text})]`;
    case "gate":
      return `${node.id}{{${text}}}`;
    case "artifact":
      return `${node.id}[/${text}/]`;
    case "sink":
      return `${node.id}[[${text}]]`;
    default:
      return `${node.id}[${text}]`;
  }
}

function mermaidArrow(edge: DiagramEdge): string {
  const label = edge.label ? `|"${edge.label}"|` : "";
  switch (edge.kind) {
    /* Thick, because a control edge governs rather than carries. */
    case "control":
      return `==>${label}`;
    case "feedback":
    case "refused":
      return `-.->${label}`;
    default:
      return `-->${label}`;
  }
}

function toMermaid(diagram: ProjectDiagram): string {
  const lines: string[] = [];
  lines.push(`%% ${diagram.title}`);
  lines.push(`%% ${diagram.caption}`);
  lines.push("%%");
  lines.push("%% Generated by scripts/export-diagrams.ts from src/content/diagrams/.");
  lines.push("%% Do not edit: the next export overwrites it.");
  lines.push("%%");
  lines.push("%% Shapes: ([source]) [process] [(store)] {{gate}} [/artifact/] [[sink]]");
  lines.push("%% Arrows: --> data   ==> control   -.-> feedback or refused");
  lines.push("flowchart LR");

  /* Group by column, so Mermaid's own layout lands close to the site's. */
  const cols = [...new Set(diagram.nodes.map((n) => n.col))].sort((a, b) => a - b);
  for (const col of cols) {
    const inCol = diagram.nodes.filter((n) => n.col === col).sort((a, b) => a.row - b.row);
    if (inCol.length === 1) {
      lines.push(`  ${mermaidShape(inCol[0])}`);
      continue;
    }
    lines.push(`  subgraph col${col} [" "]`);
    lines.push("    direction TB");
    for (const node of inCol) lines.push(`    ${mermaidShape(node)}`);
    lines.push("  end");
  }

  lines.push("");
  for (const edge of diagram.edges) {
    lines.push(`  ${edge.from} ${mermaidArrow(edge)} ${edge.to}`);
  }

  /* Subgraph containers are grouping only; drawing their boxes would imply a component. */
  lines.push("");
  for (const col of cols) {
    if (diagram.nodes.filter((n) => n.col === col).length > 1) {
      lines.push(`  style col${col} fill:none,stroke:none`);
    }
  }

  return `${lines.join("\n")}\n`;
}

/* ----------------------------------------------------------------------------------------------
 * Draw.io
 * -------------------------------------------------------------------------------------------- */

/**
 * Escape for an XML attribute or text node.
 *
 * Draw.io node labels are HTML *inside* an XML attribute, which means they are escaped twice and
 * it matters that they are. The first pass below turns the label's own text into HTML; the second,
 * this one, turns the resulting markup into an attribute value. Running only the inner pass - the
 * first version of this exporter - emitted `value="<b>Label</b>"` with live angle brackets, and
 * every generated file was malformed XML that diagrams.net refused to open.
 */
const xml = (value: string) =>
  value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

/** The inner pass: text going into the HTML that will itself be escaped by `xml`. */
const htmlText = (value: string) =>
  value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** diagrams.net style strings. Kept close to the site's own rendering of each kind. */
function drawioStyle(node: DiagramNode): string {
  const base = "whiteSpace=wrap;html=1;fontFamily=Helvetica;fontSize=13;align=left;spacingLeft=10;";
  switch (node.kind) {
    case "source":
      return `${base}rounded=1;strokeWidth=2;fillColor=#FFFFFF;strokeColor=#1C2430;`;
    case "store":
      return `shape=cylinder3;boundedLbl=1;html=1;whiteSpace=wrap;fillColor=#EBEEF3;strokeColor=#5A6675;`;
    case "gate":
      return `${base}rounded=0;strokeWidth=2;fillColor=#FFFFFF;strokeColor=#4A5B6C;`;
    case "artifact":
      return `${base}rounded=1;dashed=1;fillColor=#EBEEF3;strokeColor=#5A6675;`;
    case "sink":
      return `${base}rounded=1;strokeWidth=2;fillColor=#EBEEF3;strokeColor=#1C2430;`;
    default:
      return `${base}rounded=1;fillColor=#FFFFFF;strokeColor=#5A6675;`;
  }
}

function drawioEdgeStyle(edge: DiagramEdge): string {
  const base = "edgeStyle=orthogonalEdgeStyle;rounded=1;html=1;fontSize=11;";
  switch (edge.kind) {
    case "control":
      return `${base}strokeColor=#4A5B6C;strokeWidth=2;`;
    case "feedback":
      return `${base}strokeColor=#5A6675;dashed=1;`;
    case "refused":
      return `${base}strokeColor=#5A6675;dashed=1;endArrow=open;endFill=0;`;
    default:
      return `${base}strokeColor=#1C2430;`;
  }
}

function toDrawio(diagram: ProjectDiagram): string {
  const cells: string[] = [];
  let id = 2;
  const cellId = new Map<string, string>();

  for (const node of diagram.nodes) {
    const nid = `n${id++}`;
    cellId.set(node.id, nid);
    /* The note goes in the box, as a second line, the way the site draws it. */
    const labelHtml = node.note
      ? `<b>${htmlText(node.label)}</b><br/><font style="font-size:10px;color:#5A6675">${htmlText(node.note)}</font>`
      : `<b>${htmlText(node.label)}</b>`;
    cells.push(
      `        <mxCell id="${nid}" value="${xml(labelHtml)}" style="${drawioStyle(node)}" vertex="1" parent="1">\n` +
        `          <mxGeometry x="${nodeX(node.col)}" y="${nodeY(node.row)}" width="${NODE_W}" height="${NODE_H}" as="geometry" />\n` +
        `        </mxCell>`,
    );
  }

  for (const edge of diagram.edges) {
    const from = cellId.get(edge.from);
    const to = cellId.get(edge.to);
    if (!from || !to) continue;
    const eid = `e${id++}`;
    cells.push(
      `        <mxCell id="${eid}" value="${xml(edge.label ?? "")}" style="${drawioEdgeStyle(edge)}" ` +
        `edge="1" parent="1" source="${from}" target="${to}">\n` +
        `          <mxGeometry relative="1" as="geometry" />\n` +
        `        </mxCell>`,
    );
  }

  const width = Math.max(...diagram.nodes.map((n) => nodeX(n.col))) + NODE_W + 40;
  const height = channelY(diagram.nodes) + 40;

  return (
    `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<!-- ${xml(diagram.title)} -->\n` +
    `<!-- Generated by scripts/export-diagrams.ts from src/content/diagrams/. Do not edit. -->\n` +
    `<mxfile host="app.diagrams.net">\n` +
    `  <diagram name="${xml(diagram.slug)}">\n` +
    `    <mxGraphModel dx="${width}" dy="${height}" grid="1" gridSize="10" page="1" ` +
    `pageWidth="${width}" pageHeight="${height}" math="0" shadow="0">\n` +
    `      <root>\n` +
    `        <mxCell id="0" />\n` +
    `        <mxCell id="1" parent="0" />\n` +
    cells.join("\n") +
    `\n      </root>\n` +
    `    </mxGraphModel>\n` +
    `  </diagram>\n` +
    `</mxfile>\n`
  );
}

/* -------------------------------------------------------------------------------------------- */

mkdirSync(OUT, { recursive: true });

for (const diagram of allDiagrams) {
  writeFileSync(resolve(OUT, `${diagram.slug}.mmd`), toMermaid(diagram), "utf8");
  writeFileSync(resolve(OUT, `${diagram.slug}.drawio`), toDrawio(diagram), "utf8");
}

console.log(
  `Exported ${allDiagrams.length} diagram${allDiagrams.length === 1 ? "" : "s"} ` +
    `to docs/diagrams/ as .mmd and .drawio.`,
);
