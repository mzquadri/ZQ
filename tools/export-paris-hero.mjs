/**
 * Draw the real Paris road network for the home page hero.
 *
 * Source: `_portfolio-work/github/scenes3d/data/paris_features.json`, written by
 * `export_paris_features.py` from `datalist_batch_1.pt` with torch. That is the
 * same tensor the thesis trained on: 31,635 road segments, each a node in the
 * line graph, with its two endpoints in WGS84.
 *
 * **This draws a subset, and the page says so.** All 31,635 segments come to
 * about 23,600 distinct strokes once quantised, which is roughly 390 KB of path
 * data and that many SVG subpaths to animate. The hero takes the longest
 * segments instead: longest-first selects the boulevards and the Peripherique,
 * which is what makes the shape legible as Paris at this size. The count is
 * printed into the file and quoted in the page, because a drawing described as
 * "the Paris network" that is really a fifth of it is the kind of small
 * dishonesty this site exists not to commit.
 *
 * Output is a plain SVG with one <path> per bucket, so the hero can animate the
 * buckets in sequence rather than 6,000 separate elements.
 *
 *   node tools/export-paris-hero.mjs [count]
 */
import { readFile, writeFile } from "node:fs/promises";

const SRC =
  "D:/github-projects/_portfolio-work/github/scenes3d/data/paris_features.json";
const COUNT = Number(process.argv[2] ?? 6000);
const GRID = 1400;
const BUCKETS = 6;

const d = JSON.parse(await readFile(SRC, "utf8"));
const { ax, ay, bx, by, n } = d;

// Equirectangular about the mean latitude. Over one city the error is far below
// a pixel, and it avoids shipping a projection library for a background image.
const lat0 = ay.reduce((a, b) => a + b, 0) / n;
const k = Math.cos((lat0 * Math.PI) / 180);

let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
for (let i = 0; i < n; i++) {
  for (const [lx, ly] of [[ax[i], ay[i]], [bx[i], by[i]]]) {
    const x = lx * k;
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (ly < minY) minY = ly;
    if (ly > maxY) maxY = ly;
  }
}
const spanY = maxY - minY;
const s = GRID / spanY;
const W = Math.round((maxX - minX) * s);
const H = GRID;

const segments = [];
for (let i = 0; i < n; i++) {
  const x1 = Math.round((ax[i] * k - minX) * s);
  const y1 = Math.round((maxY - ay[i]) * s);
  const x2 = Math.round((bx[i] * k - minX) * s);
  const y2 = Math.round((maxY - by[i]) * s);
  if (x1 === x2 && y1 === y2) continue;
  segments.push({ x1, y1, x2, y2, len: Math.hypot(x2 - x1, y2 - y1) });
}

// Longest first, then dedupe: two segments quantising to the same pair of
// endpoints draw the same stroke twice.
segments.sort((a, b) => b.len - a.len);
const seen = new Set();
const kept = [];
for (const g of segments) {
  const key = `${Math.min(g.x1, g.x2)},${Math.min(g.y1, g.y2)},${Math.max(g.x1, g.x2)},${Math.max(g.y1, g.y2)}`;
  if (seen.has(key)) continue;
  seen.add(key);
  kept.push(g);
  if (kept.length >= COUNT) break;
}

/*
 * Buckets are drawn in a shuffled-but-fixed order rather than longest-first, so
 * the reveal fills the map evenly instead of drawing every big road and then
 * stippling in the small ones. The order is derived from the index, so it is
 * identical on every run: a figure that differs between renders cannot be
 * screenshotted or compared.
 */
const paths = Array.from({ length: BUCKETS }, () => []);
kept.forEach((g, i) => {
  paths[(i * 7 + (i % 3)) % BUCKETS].push(`M${g.x1} ${g.y1}L${g.x2} ${g.y2}`);
});

const body = paths
  .map((p, i) => `<path class="pr pr${i}" d="${p.join("")}"/>`)
  .join("\n");

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" fill="none" stroke="currentColor" stroke-width="1.1" stroke-linecap="round">
<!--
  The real Paris road network from the thesis tensor, ${kept.length} of ${n} road
  segments, the longest first. Generated by tools/export-paris-hero.mjs from
  datalist_batch_1.pt via paris_features.json. Not hand-drawn and not decorative
  geometry: every stroke is a road segment the surrogate was trained on.
-->
${body}
</svg>
`;

const out = `public/media/paris-network-${kept.length}.svg`;
await writeFile(out, svg, "utf8");
console.log(`  ${out}`);
console.log(`     ${kept.length} of ${n} segments, viewBox ${W} x ${H}, ${(svg.length / 1024).toFixed(0)} KB`);
