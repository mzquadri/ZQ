# The integrity gate. Nothing is emitted unless the reference run is reproduced.
def check(name, got, want, tol=5e-4):
    for key, published_key in [("RMSE", "RMSE"), ("MAE", "MAE"), ("R2", "R2"), ("MAPE", "MAPE")]:
        a, b = got[key], want[published_key]
        assert abs(a - b) <= tol * max(1.0, abs(b)), (
            "%s %s: recomputed %.6f but results/forecast_results.json says %.6f"
            % (name, key, a, b))
    print("  %-16s reproduced exactly" % name)


