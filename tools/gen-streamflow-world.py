def generate_streamflow(n_years=15, seed=42):
    rng = np.random.RandomState(seed)
    n_days = n_years * 365
    dates = pd.date_range(start="2008-01-01", periods=n_days, freq="D")
    doy = dates.dayofyear.values.astype(float)
    seasonal = 50 + 30 * np.sin(2 * np.pi * (doy - 90) / 365)
    trend = 0.005 * np.arange(n_days)
    rain_prob = 0.3 + 0.15 * np.sin(2 * np.pi * (doy - 30) / 365)
    rain_occur = rng.binomial(1, np.clip(rain_prob, 0.1, 0.6))
    rain_amount = rng.exponential(8, n_days) * rain_occur
    extreme = rng.binomial(1, 0.004, n_days).astype(bool)
    rain_amount[extreme] *= rng.uniform(4, 10, extreme.sum())
    precip = np.maximum(rain_amount, 0)
    streamflow = np.zeros(n_days)
    streamflow[0] = 50.0
    for t in range(1, n_days):
        ar = 0.85 * streamflow[t - 1]
        base_pull = 0.15 * seasonal[t]
        rr = 0.0
        for lag, w in enumerate([0.3, 0.25, 0.2, 0.15, 0.1]):
            idx = t - lag
            if idx >= 0:
                rr += w * precip[idx] * 0.8
        streamflow[t] = ar + base_pull + rr + trend[t] + rng.normal(0, 2.0)
        streamflow[t] = max(streamflow[t], 5.0)
    temperature = 10 + 15 * np.sin(2 * np.pi * (doy - 100) / 365) + rng.normal(0, 3, n_days)
    return pd.DataFrame({
        "date": dates,
        TARGET: np.round(streamflow, 2),
        "precipitation_mm": np.round(precip, 2),
        "temperature_c": np.round(temperature, 2),
    })


LAGS = [1, 2, 3, 7, 14, 30, 365]
ROLL = [7, 14, 30]
PRECIP_LAGS = [1, 2, 3, 7]


def create_lag_features(df):
    """src/forecast.py, verbatim."""
    r = df.copy()
    r["dayofyear"] = r.date.dt.dayofyear
    r["month"] = r.date.dt.month
    r["dayofweek"] = r.date.dt.dayofweek
    r["year"] = r.date.dt.year
    r["month_sin"] = np.sin(2 * np.pi * r.month / 12)
    r["month_cos"] = np.cos(2 * np.pi * r.month / 12)
    r["doy_sin"] = np.sin(2 * np.pi * r.dayofyear / 365)
    r["doy_cos"] = np.cos(2 * np.pi * r.dayofyear / 365)
    for lag in LAGS:
        r[TARGET + "_lag" + str(lag)] = r[TARGET].shift(lag)
    for w in ROLL:
        r[TARGET + "_roll_mean_" + str(w)] = r[TARGET].shift(1).rolling(w).mean()
        r[TARGET + "_roll_std_" + str(w)] = r[TARGET].shift(1).rolling(w).std()
    for lag in PRECIP_LAGS:
        r["precip_lag" + str(lag)] = r["precipitation_mm"].shift(lag)
    r["precip_roll_7"] = r["precipitation_mm"].shift(1).rolling(7).sum()
    return r.dropna()


def metrics(act, pred):
    act = np.asarray(act, dtype=float)
    pred = np.asarray(pred, dtype=float)
    rmse = float(np.sqrt(np.mean((act - pred) ** 2)))
    mae = float(np.mean(np.abs(act - pred)))
    r2 = float(1 - np.sum((act - pred) ** 2) / np.sum((act - act.mean()) ** 2))
    mape = float(np.mean(np.abs((act - pred) / act)) * 100)
    return dict(RMSE=rmse, MAE=mae, R2=r2, MAPE=mape)


